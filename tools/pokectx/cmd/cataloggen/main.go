package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var definePattern = regexp.MustCompile(`^#define\s+([A-Z][A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|[0-9]+)\b`)

func main() {
	root := flag.String("root", "..", "pokeemerald repository root")
	output := flag.String("output", "generated.go", "generated Go output")
	flag.Parse()
	maps, err := readMaps(filepath.Join(*root, "data/maps/map_groups.json"))
	if err != nil {
		fail(err)
	}
	species, err := readDefines(filepath.Join(*root, "include/constants/species.h"), "SPECIES_")
	if err != nil {
		fail(err)
	}
	moves, err := readDefines(filepath.Join(*root, "include/constants/moves.h"), "MOVE_")
	if err != nil {
		fail(err)
	}
	items, err := readDefines(filepath.Join(*root, "include/constants/items.h"), "ITEM_")
	if err != nil {
		fail(err)
	}
	content := "package catalog\n\n// Code generated by cataloggen from the pokeemerald decompilation. DO NOT EDIT.\n\nvar Default = Catalog{\n"
	content += render("Maps", maps) + render("Species", species) + render("Moves", moves) + render("Items", items) + "}\n"
	formatted, err := format.Source([]byte(content))
	if err != nil {
		fail(fmt.Errorf("format generated catalog: %w", err))
	}
	if err := os.WriteFile(*output, formatted, 0o644); err != nil {
		fail(err)
	}
}

func readMaps(path string) (map[uint16]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var groups struct {
		GroupOrder []string `json:"group_order"`
	}
	var raw map[string]json.RawMessage
	if err := json.Unmarshal(data, &groups); err != nil {
		return nil, err
	}
	if err := json.Unmarshal(data, &raw); err != nil {
		return nil, err
	}
	result := make(map[uint16]string)
	for group, key := range groups.GroupOrder {
		var names []string
		if err := json.Unmarshal(raw[key], &names); err != nil {
			return nil, err
		}
		for number, name := range names {
			result[uint16(group<<8|number)] = "MAP_" + screamingSnake(name)
		}
	}
	return result, nil
}

func readDefines(path, prefix string) (map[uint16]string, error) {
	file, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	result := make(map[uint16]string)
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		match := definePattern.FindStringSubmatch(scanner.Text())
		if len(match) != 3 || !strings.HasPrefix(match[1], prefix) {
			continue
		}
		value, err := strconv.ParseUint(match[2], 0, 16)
		if err != nil {
			return nil, err
		}
		if _, exists := result[uint16(value)]; !exists {
			result[uint16(value)] = match[1]
		}
	}
	return result, scanner.Err()
}

func render(field string, values map[uint16]string) string {
	keys := make([]int, 0, len(values))
	for key := range values {
		keys = append(keys, int(key))
	}
	sort.Ints(keys)
	var builder strings.Builder
	fmt.Fprintf(&builder, "\t%s: map[uint16]string{\n", field)
	for _, key := range keys {
		fmt.Fprintf(&builder, "\t\t0x%04X: %q,\n", key, values[uint16(key)])
	}
	builder.WriteString("\t},\n")
	return builder.String()
}

func screamingSnake(value string) string {
	var result strings.Builder
	for index, char := range value {
		if index > 0 && char >= 'A' && char <= 'Z' {
			previous := rune(value[index-1])
			if previous != '_' && (previous >= 'a' && previous <= 'z' || previous >= '0' && previous <= '9') {
				result.WriteByte('_')
			}
		}
		result.WriteRune(char)
	}
	return strings.ToUpper(result.String())
}

func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }
